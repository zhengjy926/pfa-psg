/*
 * ECSP response codes (PRM-026, ECSP table 3-4).
 */
#ifndef PSG_APP_ECSP_ECSP_CODES_H
#define PSG_APP_ECSP_ECSP_CODES_H

#define ECSP_RSP_SUCCESS 0x00u
#define ECSP_RSP_ERROR 0x01u
#define ECSP_RSP_BAD_LENGTH 0x02u
#define ECSP_RSP_BAD_PARAMETER 0x03u
#define ECSP_RSP_UNSUPPORTED 0x04u
#define ECSP_RSP_NOT_HANDSHAKEN 0x10u
#define ECSP_RSP_BUSY 0x11u
#define ECSP_RSP_MODE 0x12u
#define ECSP_RSP_PRECONDITION 0x13u
#define ECSP_RSP_LOCKED 0x14u
#define ECSP_RSP_SAFETY 0x15u
#define ECSP_RSP_EXECUTION_FAILED 0x20u

/* Generic command codes (PRM-024). */
#define ECSP_CMD_HANDSHAKE 0x01u
#define ECSP_CMD_GET_SW_VERSION 0x02u
#define ECSP_CMD_SET_HW_VERSION 0x03u
#define ECSP_CMD_GET_HW_VERSION 0x04u
#define ECSP_CMD_SET_SERIAL 0x05u
#define ECSP_CMD_GET_SERIAL 0x06u
#define ECSP_CMD_RESET 0x07u
#define ECSP_CMD_SET_UPLOAD_MODE 0x0Fu
#define ECSP_CMD_HEARTBEAT 0x10u
#define ECSP_CMD_FAULT_REPORT 0x11u
#define ECSP_CMD_GET_FAULT 0x12u

#endif /* PSG_APP_ECSP_ECSP_CODES_H */
